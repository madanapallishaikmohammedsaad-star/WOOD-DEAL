package com.example.util

import com.example.data.model.DealWithDetails
import java.text.NumberFormat
import java.text.SimpleDateFormat
import java.util.Date
import java.util.Locale

object CurrencyUtils {

    fun formatRupee(amount: Double): String {
        val longVal = amount.toLong()
        // If it's a whole number, format without decimals
        if (amount == longVal.toDouble()) {
            val format = NumberFormat.getCurrencyInstance(Locale("en", "IN"))
            val formatted = format.format(longVal)
            // Replace standard INR prefix if needed with ₹
            return formatted.replace("INR", "₹").replace(".00", "").trim()
        } else {
            val format = NumberFormat.getCurrencyInstance(Locale("en", "IN"))
            return format.format(amount).replace("INR", "₹").trim()
        }
    }

    fun formatPercent(percent: Double): String {
        return if (percent == percent.toLong().toDouble()) {
            "${percent.toLong()}%"
        } else {
            String.format(Locale.getDefault(), "%.1f%%", percent)
        }
    }

    fun getTodayFormatted(): String {
        val sdf = SimpleDateFormat("dd MMM yyyy", Locale.getDefault())
        return sdf.format(Date())
    }

    fun generateWhatsAppDealSummary(dealWithDetails: DealWithDetails): String {
        val deal = dealWithDetails.deal
        val totalCost = dealWithDetails.totalCost
        val totalSales = dealWithDetails.totalSales
        val profit = dealWithDetails.profit
        val isProfit = profit >= 0

        val sb = StringBuilder()
        sb.append("📋 *DEAL REPORT: ${deal.name.uppercase()}*\n")
        sb.append("📍 *Location:* ${deal.location}\n")
        sb.append("📅 *Date:* ${deal.date}\n")
        sb.append("🏷️ *Status:* ${if (deal.isCompleted) "🟢 COMPLETE" else "🟡 IN PROGRESS"}\n\n")

        sb.append("💰 *FINANCIAL SUMMARY:*\n")
        sb.append("• Purchase Price: ${formatRupee(deal.purchasePrice)}\n")
        sb.append("• Other Expenses: ${formatRupee(dealWithDetails.totalExpenses)}\n")
        sb.append("• *TOTAL COST:* ${formatRupee(totalCost)}\n")
        sb.append("• *TOTAL SALES:* ${formatRupee(totalSales)}\n")
        sb.append("• Cash Received: ${formatRupee(dealWithDetails.totalReceived)}\n")
        if (dealWithDetails.totalPending > 0) {
            sb.append("• Pending Dues: ${formatRupee(dealWithDetails.totalPending)}\n")
        }
        sb.append("• *${if (isProfit) "PROFIT" else "LOSS"}:* ${formatRupee(profit)}\n\n")

        if (dealWithDetails.partners.isNotEmpty()) {
            sb.append("👥 *PARTNER SHARE & PAYOUTS:*\n")
            dealWithDetails.partnerPayouts.forEach { partner ->
                sb.append("• *${partner.name}* (${formatPercent(partner.percentage)})\n")
                sb.append("   - Invested: ${formatRupee(partner.amountInvested)}\n")
                sb.append("   - ${if (partner.profitShare >= 0) "Profit" else "Loss"}: ${formatRupee(partner.profitShare)}\n")
                sb.append("   - *Total Return: ${formatRupee(partner.totalReturn)}*\n")
            }
            sb.append("\n")
        }

        if (dealWithDetails.expenses.isNotEmpty()) {
            sb.append("💸 *EXPENSES BREAKDOWN:*\n")
            dealWithDetails.expenses.forEach { exp ->
                sb.append("• ${exp.categoryIcon} ${exp.name}: ${formatRupee(exp.amount)}\n")
            }
            sb.append("\n")
        }

        if (dealWithDetails.sales.isNotEmpty()) {
            sb.append("🪵 *SALES BREAKDOWN:*\n")
            dealWithDetails.sales.forEach { sale ->
                sb.append("• ${sale.itemName} (${sale.customerName}): ${formatRupee(sale.sellingPrice)} [Recv: ${formatRupee(sale.amountReceived)}]\n")
            }
            sb.append("\n")
        }

        sb.append("Generated by Wood Deal Accounting")
        return sb.toString()
    }

    /**
     * Generates a tabular column analysis formatted for WhatsApp sharing:
     * Partner Name | Invested Amount | Percentage | Profit Amount | Total Received
     * with Total Investment, Total Profit, and Total Received below it.
     */
    fun generatePartnerTabularWhatsApp(dealWithDetails: DealWithDetails): String {
        val deal = dealWithDetails.deal
        val totalInvested = dealWithDetails.totalInvested
        val totalProfit = dealWithDetails.profit
        val totalReturn = totalInvested + totalProfit
        val payouts = dealWithDetails.partnerPayouts

        val sb = StringBuilder()
        sb.append("📊 *PARTNER ANALYSIS TABLE: ${deal.name.uppercase()}*\n")
        sb.append("📍 *Location:* ${deal.location} | 📅 *Date:* ${deal.date}\n")
        sb.append("🏷️ *Status:* ${if (deal.isCompleted) "🟢 COMPLETE" else "🟡 IN PROGRESS"}\n\n")

        sb.append("```\n")
        sb.append("| Partner Name | Invested Amount | Percentage | Profit Amount | Total Received |\n")
        sb.append("|---|---|---|---|---|\n")

        payouts.forEach { p ->
            val profSign = if (p.profitShare >= 0) "+" else ""
            sb.append("| ${p.name} | ${formatRupee(p.amountInvested)} | ${formatPercent(p.percentage)} | $profSign${formatRupee(p.profitShare)} | ${formatRupee(p.totalReturn)} |\n")
        }

        sb.append("| TOTAL | ${formatRupee(totalInvested)} | 100% | ${if (totalProfit >= 0) "+" else ""}${formatRupee(totalProfit)} | ${formatRupee(totalReturn)} |\n")
        sb.append("```\n\n")

        sb.append("📌 *KEY TOTALS:*\n")
        sb.append("• *Total Investment:* ${formatRupee(totalInvested)}\n")
        sb.append("• *Total Profit:* ${formatRupee(totalProfit)}\n")
        sb.append("• *Total Received (Payout):* ${formatRupee(totalReturn)}\n")
        sb.append("• *Total Sales:* ${formatRupee(dealWithDetails.totalSales)}\n")
        sb.append("• *Total Cost:* ${formatRupee(dealWithDetails.totalCost)}\n\n")
        sb.append("_Generated by Wood Deal Accounting_")

        return sb.toString()
    }

    /**
     * Generates an overall tabular column analysis across all deals for WhatsApp.
     */
    fun generateOverallPartnerTabularWhatsApp(
        partners: List<com.example.ui.screens.PartnerAggregate>,
        totalInvested: Double,
        totalProfit: Double,
        totalReturn: Double
    ): String {
        val sb = StringBuilder()
        sb.append("📊 *OVERALL PARTNER ANALYSIS TABLE*\n")
        sb.append("📅 *Date:* ${getTodayFormatted()}\n\n")

        sb.append("```\n")
        sb.append("| Partner Name | Invested Amount | Percentage | Profit Amount | Total Received |\n")
        sb.append("|---|---|---|---|---|\n")

        partners.forEach { p ->
            val pct = if (totalInvested > 0) (p.totalInvested / totalInvested) * 100.0 else 0.0
            val profSign = if (p.totalProfitShare >= 0) "+" else ""
            sb.append("| ${p.name} | ${formatRupee(p.totalInvested)} | ${formatPercent(pct)} | $profSign${formatRupee(p.totalProfitShare)} | ${formatRupee(p.totalReturn)} |\n")
        }

        sb.append("| TOTAL | ${formatRupee(totalInvested)} | 100% | ${if (totalProfit >= 0) "+" else ""}${formatRupee(totalProfit)} | ${formatRupee(totalReturn)} |\n")
        sb.append("```\n\n")

        sb.append("📌 *OVERALL TOTALS:*\n")
        sb.append("• *Total Investment:* ${formatRupee(totalInvested)}\n")
        sb.append("• *Total Profit:* ${formatRupee(totalProfit)}\n")
        sb.append("• *Total Received (Payout):* ${formatRupee(totalReturn)}\n\n")
        sb.append("_Generated by Wood Deal Accounting_")

        return sb.toString()
    }
}
